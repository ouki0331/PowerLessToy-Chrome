// Helper to create mock DOM elements
function createMockElement({
  tag = 'div',
  id = '',
  classes = [],
  attributes = {},
  textContent = '',
  parent = null
}) {
  const classSet = new Set(classes);
  const attrMap = { ...attributes };
  if (id) attrMap.id = id;

  const element = {
    tagName: tag.toUpperCase(),
    nodeType: 1,
    id,
    classList: {
      length: classSet.size,
      has: cls => classSet.has(cls),
      [Symbol.iterator]: () => classSet.values(),
      filter: fn => Array.from(classSet).filter(fn),
      map: fn => Array.from(classSet).map(fn),
      find: fn => Array.from(classSet).find(fn)
    },
    getAttribute: name => attrMap[name] || null,
    setAttribute: (name, val) => { attrMap[name] = String(val); },
    textContent,
    parentElement: parent,
    children: []
  };

  if (parent && parent.children) {
    parent.children.push(element);
  }

  return element;
}

// Mock querySelectorAll root
function createMockRoot(elements) {
  return {
    querySelectorAll(selector) {
      return elements.filter(el => {
        // Simple mock selector matcher for unit tests
        if (selector.startsWith('#')) {
          const id = selector.slice(1);
          return el.id === id;
        }
        if (selector.includes('[data-testid="')) {
          const m = selector.match(/\[data-testid="([^"]+)"\]/);
          return m && el.getAttribute('data-testid') === m[1];
        }
        if (selector.includes('.')) {
          const [tag, ...cls] = selector.split('.');
          if (tag && el.tagName.toLowerCase() !== tag.toLowerCase()) return false;
          return cls.every(c => el.classList.has(c));
        }
        if (selector === el.tagName.toLowerCase()) {
          return true;
        }
        return false;
      });
    }
  };
}

test('isStableId distinguishes stable semantic IDs from autogenerated IDs', () => {
  assert.equal(isStableId('main-header'), true);
  assert.equal(isStableId('sidebar_nav'), true);
  assert.equal(isStableId('comments-section'), true);

  // Dynamic framework generated
  assert.equal(isStableId(':r1:'), false);
  assert.equal(isStableId('comp-987654'), false);
  assert.equal(isStableId('ember1234'), false);
  assert.equal(isStableId('react-root-382947'), false);
  assert.equal(isStableId('6c4176f1624cea84'), false);
});

test('isMeaningfulClass filters out hashed and framework class names', () => {
  assert.equal(isMeaningfulClass('sidebar-ad'), true);
  assert.equal(isMeaningfulClass('promo_banner'), true);
  assert.equal(isMeaningfulClass('recommendation-list'), true);

  // Hashed or framework generated
  assert.equal(isMeaningfulClass('css-1h8z7d'), false);
  assert.equal(isMeaningfulClass('sc-bdVaJa'), false);
  assert.equal(isMeaningfulClass('jsx-18293'), false);
  assert.equal(isMeaningfulClass('_2XkLm89qwe'), false);
});

test('getElementFriendlyName extracts informative label for user', () => {
  const el1 = createMockElement({
    tag: 'aside',
    attributes: { 'aria-label': '推荐内容' }
  });
  assert.equal(getElementFriendlyName(el1), 'aside · 推荐内容');

  const el2 = createMockElement({
    tag: 'div',
    attributes: { 'data-testid': 'sidebar-sponsor' }
  });
  assert.equal(getElementFriendlyName(el2), 'div · sidebar-sponsor');

  const el3 = createMockElement({
    tag: 'section',
    classes: ['promo-card']
  });
  assert.equal(getElementFriendlyName(el3), 'section.promo-card');

  const el4 = createMockElement({
    tag: 'p',
    textContent: '点击查看最新优惠'
  });
  assert.equal(getElementFriendlyName(el4), 'p · 点击查看最新优惠');
});

test('generateStableSelector prioritizes stable ID, semantic attribute and avoids position indices', () => {
  const elWithId = createMockElement({ tag: 'aside', id: 'sticky-ad' });
  const root1 = createMockRoot([elWithId]);
  assert.equal(generateStableSelector(elWithId, root1), '#sticky-ad');

  const elWithTestId = createMockElement({
    tag: 'div',
    attributes: { 'data-testid': 'ad-container' }
  });
  const root2 = createMockRoot([elWithTestId]);
  assert.equal(generateStableSelector(elWithTestId, root2), 'div[data-testid="ad-container"]');

  const elWithClass = createMockElement({
    tag: 'aside',
    classes: ['sidebar-banner']
  });
  const root3 = createMockRoot([elWithClass]);
  assert.equal(generateStableSelector(elWithClass, root3), 'aside.sidebar-banner');
});

test('evaluateSelectorReliability detects exact, needs_review (ambiguity), and not_matched (RULE-MATCH-001)', () => {
  const el1 = createMockElement({ tag: 'div', id: 'promo-1' });
  const el2 = createMockElement({ tag: 'div', id: 'promo-2' });

  // 1 match expected 1 -> exact
  const rootExact = {
    querySelectorAll: () => [el1]
  };
  const resExact = evaluateSelectorReliability('#promo-1', { expectedCount: 1, tag: 'div' }, rootExact);
  assert.equal(resExact.status, 'exact');
  assert.equal(resExact.count, 1);

  // Multiple matches when expected 1 -> AMBIGUITY (needs_review)
  const rootAmbiguous = {
    querySelectorAll: () => [el1, el2]
  };
  const resAmbiguous = evaluateSelectorReliability('.promo', { expectedCount: 1, tag: 'div' }, rootAmbiguous);
  assert.equal(resAmbiguous.status, 'needs_review');
  assert.equal(resAmbiguous.count, 2);

  // 0 matches -> not_matched
  const rootEmpty = {
    querySelectorAll: () => []
  };
  const resEmpty = evaluateSelectorReliability('#nonexistent', { expectedCount: 1 }, rootEmpty);
  assert.equal(resEmpty.status, 'not_matched');
  assert.equal(resEmpty.count, 0);
});
